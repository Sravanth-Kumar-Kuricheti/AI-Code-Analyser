PYTEST_SCENARIOS = [
    {"name": "Nominal Execution", "type": "Happy Path", "description": "Passes valid inputs and verifies expected return schema/value."},
    {"name": "Boundary / Null Condition", "type": "Edge Case", "description": "Validates resilience against None, empty strings, or empty lists."},
    {"name": "Exception / Fault Tolerance", "type": "Error Path", "description": "Confirms appropriate exception propagation on invalid inputs."}
]

JEST_SCENARIOS = [
    {"name": "Standard Invocation", "type": "Happy Path", "description": "Valid payload and state verification."},
    {"name": "Null/Undefined Boundary", "type": "Edge Case", "description": "Handles missing or partial parameters safely."}
]

class TestCaseGenerator:
    """Synthesizes automated unit tests (pytest / jest) based on AST metadata."""

    @staticmethod
    def generate_pytest(file_path: str, symbol_data: Dict[str, Any], file_content: str = "") -> Dict[str, Any]:
        """Generates pytest test suite with fixtures and edge case stubs."""
        fn_name = symbol_data.get("name", "target_function")
        signature = symbol_data.get("signature", f"def {fn_name}()")
        mod_path = file_path.replace("\\", "/").replace("/", ".")
        if mod_path.endswith(".py"):
            mod_path = mod_path[:-3]

        class_name = fn_name.title().replace("_", "")
        test_code = PYTEST_TEMPLATE.format(
            mod_path=mod_path,
            fn_name=fn_name,
            class_name=class_name,
            signature=signature
        )

        return {
            "framework": "pytest",
            "target_function": fn_name,
            "target_file": file_path,
            "signature": signature,
            "docstring": symbol_data.get("docstring", ""),
            "generated_test_code": test_code,
            "suggested_scenarios": PYTEST_SCENARIOS,
            "coverage_estimate_pct": 85.0
        }

    @staticmethod
    def generate_jest(file_path: str, symbol_data: Dict[str, Any]) -> Dict[str, Any]:
        """Generates Jest TypeScript/JavaScript unit test suite."""
        fn_name = symbol_data.get("name", "targetFunction")
        rel_import = f"./{Path(file_path).stem}"
        test_code = JEST_TEMPLATE.format(fn_name=fn_name, rel_import=rel_import)

        return {
            "framework": "jest",
            "target_function": fn_name,
            "target_file": file_path,
            "signature": symbol_data.get("signature", ""),
            "generated_test_code": test_code,
            "suggested_scenarios": JEST_SCENARIOS,
            "coverage_estimate_pct": 82.0
        }
